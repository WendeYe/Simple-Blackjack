# Simple implementation of blackjack logic
# This blackjack game will feature 4 decks, totalling 208 cards (52 * 4)
# Dealer will hit on soft 17 (Ace + 6), hit on 16 and stand on 17+
import os
from cryptography.hazmat.primitives import hashes, hmac


def createDeck():
    suits = ["Diamonds", "Hearts", "Clubs", "Spades"]
    values = ["Ace", "2", "3", "4", "5", "6", "7", "8", "9", "10", "Jack", "Queen", "King"]
    # just a loop that takes every number and adds it to the deck alongisde each suit
    initial_deck = [f"{value} of {suit}" for value in values for suit in suits]
    # we create 4 decks
    deck = initial_deck * 4
    return deck


# I want to implement a system like provably fair that takes a seed generated by the player, a seed generated by the server, and using both of them I can shuffle the deck
# ensuring 'fairness', as fair as gambling can be as the house always has an edge
